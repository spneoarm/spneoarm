class Canvas:
    def __init__(self, w, h, px=4):
        self.w, self.h, self.px = w, h, px
        self.layers = {"base": {}}
        self.order = ["base"]

    def layer(self, name):
        if name not in self.layers:
            self.layers[name] = {}
            self.order.append(name)
        return name

    def set(self, x, y, c, layer="base"):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.layers[layer][(x, y)] = c

    def rect(self, x, y, w, h, c, layer="base"):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                self.set(xx, yy, c, layer)

    def frame(self, x, y, w, h, c):
        self.rect(x, y, w, 1, c)
        self.rect(x, y + h - 1, w, 1, c)
        self.rect(x, y, 1, h, c)
        self.rect(x + w - 1, y, 1, h, c)

    @staticmethod
    def text_width(s, scale=1):
        return len(s) * 6 * scale - scale

    def text(self, s, x, y, c, scale=1, layer="base", shadow=None):
        if shadow:
            sc, off = shadow
            self.text(s, x + off, y + off, sc, scale, layer)
        for i, ch in enumerate(s.upper()):
            for gy, row in enumerate(FONT[ch]):
                for gx, v in enumerate(row):
                    if v == "#":
                        self.rect(x + (i * 6 + gx) * scale, y + gy * scale, scale, scale, c, layer)

    def text_center(self, s, cx, y, c, scale=1, layer="base"):
        self.text(s, cx - self.text_width(s, scale) // 2, y, c, scale, layer)

    def _rects(self, cells):
        # Merge horizontal runs per row, then stack identical runs vertically.
        runs = {}
        for (x, y), c in cells.items():
            runs.setdefault(y, []).append((x, c))
        row_runs = []
        for y in sorted(runs):
            xs = sorted(runs[y])
            start, prev, col = xs[0][0], xs[0][0], xs[0][1]
            for x, c in xs[1:] + [(None, None)]:
                if x == prev + 1 and c == col:
                    prev = x
                    continue
                row_runs.append((start, y, prev - start + 1, col))
                if x is not None:
                    start, prev, col = x, x, c
        open_ = {}
        out = []
        for x, y, w, c in row_runs:
            key = (x, w, c)
            if key in open_ and open_[key][1] + open_[key][3] == y:
                rx, ry, rw, rh, rc = open_[key]
                open_[key] = (rx, ry, rw, rh + 1, rc)
            else:
                if key in open_:
                    out.append(open_[key])
                open_[key] = (x, y, w, 1, c)
        out.extend(open_.values())
        return out

    def svg(self, label, css="", extra=""):
        p = self.px
        W, H = self.w * p, self.h * p
        parts = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" '
            f'viewBox="0 0 {W} {H}" role="img" aria-label="{label}" shape-rendering="crispEdges">',
            f"<title>{label}</title>",
        ]
        if css:
            parts.append(f"<style>{css}@media (prefers-reduced-motion: reduce){{*{{animation:none!important}}}}</style>")
        for name in self.order:
            rects = self._rects(self.layers[name])
            body = "".join(
                f'<rect x="{x*p}" y="{y*p}" width="{w*p}" height="{h*p}" fill="{c}"/>'
                for x, y, w, h, c in sorted(rects, key=lambda r: (r[4], r[1], r[0]))
            )
            parts.append(body if name == "base" else f'<g class="{name}">{body}</g>')
        parts.append(extra)
        parts.append("</svg>")
        return "".join(parts)
